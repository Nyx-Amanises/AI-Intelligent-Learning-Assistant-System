#!/usr/bin/env python3
"""Package reviewed, complete textbook PDFs from one or more local manifests.

Requires PyMuPDF and Pillow. This command is offline: it never downloads books,
executes SQL, or changes an original PDF. Pass all candidate manifests to produce
the complete batch. --check validates the same outputs without writing files.

Example:
    python db/catalog/package_foundation_books.py math.json science.json general.json
    python db/catalog/package_foundation_books.py db/catalog/github-foundation-books.json --check

The published manifest can be checked or rebuilt using its already packaged PDFs;
machine-specific input paths are deliberately omitted from published metadata.
"""
import argparse
import hashlib
from io import BytesIO
import json
import os
from pathlib import Path
import re
import shutil
import tempfile

import fitz
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'frontend/public/open-books'
MANIFEST = ROOT / 'db/catalog/github-foundation-books.json'
CONFIG = ROOT / 'frontend/src/config/foundationBookReading.ts'
LICENSES = ROOT / 'db/catalog/licenses'
PAGE_BREAK = '\n\n\f\n\n'
PUBLIC_FIELDS = {
    'slug', 'title', 'officialTitle', 'subtitle', 'author', 'publisher', 'publisherNote',
    'languageCode', 'subject', 'licenseCode', 'licenseUrl', 'sourceUrl', 'originalSourceUrl',
    'downloadUrl', 'attribution', 'licenseNote', 'licenseEvidence', 'licenseEvidencePages',
    'licenseEvidenceUrls', 'licensePageNumbers', 'licensePdfPage', 'knowledgePoints',
    'summary', 'sourceName', 'coverageNote', 'completenessEvidence', 'coverAttribution',
    'coverPolicy', 'coverLicenseEvidence', 'coverLicenseNote', 'readerQualityNote',
    'isbn', 'contentsPageNumbers', 'tableOfContents', 'chapters', 'officialCoverUrl',
    'officialCoverSourceUrl', 'requiredPageAttributionText', 'requiredPageAttributionUrl',
    'pageAttributionText', 'pageAttributionUrl',
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode('utf-8')


def write_file(path, data, check):
    if check:
        require(path.is_file() and path.read_bytes() == data, f'Stale or missing generated file: {path}')
        return
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.foundation-', delete=False) as temp:
        temporary = Path(temp.name)
        temp.write(data)
    try:
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def protect_original(path, expected):
    if path.exists():
        require(path.is_file() and digest(path) == expected, f'Refusing to overwrite a different original PDF: {path}')


def attribution_file(row, license_source):
    slug = row['slug']
    cover_note = ('封面取自已授权的原始 PDF 首页，等比缩略至 480px 宽。'
                  if row['coverUrl'] == f'/open-books/{slug}/cover.webp'
                  else '未复制独立书封，列表使用默认封面或单独核验的远程封面。')
    return '\n'.join([
        '# ' + row['title'], '', row['attribution'], '',
        '- 作者：' + row['author'], '- 出版/发布方：' + row['publisher'],
        '- 版本：' + row.get('subtitle', ''), '- GitHub 来源：' + row['sourceUrl'],
        '- 作者/出版方原站：' + row.get('originalSourceUrl', row['sourceUrl']),
        '- 原始完整 PDF：' + row['downloadUrl'],
        f"- 许可：[{row['licenseCode']}]({row['licenseUrl']})",
        '- 完整许可文件：[LICENSE.txt](LICENSE.txt)',
        f"- 许可文本来源：{license_source['sourceUrl']}",
        f"- 许可打包源文件：`db/catalog/licenses/{license_source['file']}`",
        '- 核验日期：' + row['verifiedAt'], '- 许可依据：' + row['licenseEvidence'],
        f"- PDF SHA-256：`{row['sha256']}`",
        f"- body.txt SHA-256：`{row['textSha256']}`", '',
        '原始 PDF 按字节完整复制，未修改、裁切或删除页面；原有版权页、署名和许可附录均保留。',
        f"body.txt 对全部 {row['pageCount']} 页按页序提取，使用换页符保留页界，未截断任何书页；该文本沿用本书的独立许可。",
        '自动提取会改变排版，部分公式、图形及字体映射可能失真，请以原版 PDF 为准。' + cover_note,
        '若原书要求逐页署名，body.txt 保留原署名，并在缺失该声明的提取页补充原站署名和网址。', '',
        '本目录第三方教材与本应用代码采用各自独立许可证；书封、商标或个别素材另有权利声明的，仍须遵守原书声明。', '',
    ]).encode('utf-8')


def reading_config(rows):
    lines = [
        '// Generated by db/catalog/package_foundation_books.py. Do not edit by hand.',
        'export const foundationBookReading: Record<string, { preferOriginal: boolean }> = {'
    ]
    entries = [f"  '{row['documentUrl']}': {{ preferOriginal: {str(row['preferOriginal']).lower()} }}" for row in rows]
    return ('\n'.join(lines) + '\n' + ',\n'.join(entries) + '\n}\n').encode('utf-8')


def prepare(candidate, candidate_manifest, verified_at, license_index, reserved):
    slug = candidate.get('slug', '')
    require(re.fullmatch('[a-z0-9]+(?:-[a-z0-9]+)*', slug), f'Invalid book slug: {slug!r}')
    require(slug not in reserved, f'Existing original-batch book is protected: {slug}')
    folder = ASSETS / slug
    require(folder.resolve().is_relative_to(ASSETS.resolve()), f'Asset path escapes book directory: {slug}')
    raw_path = candidate.get('localPdfPath') or candidate.get('pdfPath')
    source = Path(raw_path) if raw_path else folder / 'book.pdf'
    if not source.is_absolute():
        source = candidate_manifest.parent / source
    source = source.resolve(strict=True)
    expected = candidate.get('sha256', '')
    require(re.fullmatch('[a-f0-9]{64}', expected), f'{slug}: a verified SHA-256 is required')
    require(digest(source) == expected, f'{slug}: source PDF hash mismatch')
    require(source.stat().st_size < 100 * 1024 * 1024, f'{slug}: PDF exceeds 100 MiB')
    protect_original(folder / 'book.pdf', expected)
    code = candidate.get('licenseCode')
    require(code in license_index, f'{slug}: missing reviewed full license text for {code}')
    license_source = license_index[code]
    license_path = LICENSES / license_source['file']
    require(digest(license_path) == license_source['sha256'], f'{code}: license text hash mismatch')
    for field in ('title', 'author', 'publisher', 'languageCode', 'subject', 'summary',
                  'sourceName', 'coverageNote', 'attribution', 'licenseNote', 'licenseEvidence'):
        require(isinstance(candidate.get(field), str) and candidate[field].strip(), f'{slug}: missing {field}')
    for field in ('licenseUrl', 'downloadUrl', 'sourceUrl'):
        require(isinstance(candidate.get(field), str) and candidate[field].startswith('https://'), f'{slug}: invalid {field}')
    require(candidate['sourceUrl'].startswith('https://github.com/'), f'{slug}: GitHub provenance is required')
    require(isinstance(candidate.get('knowledgePoints'), list) and
            all(isinstance(x, str) and x for x in candidate['knowledgePoints']), f'{slug}: missing knowledge points')

    row = {key: value for key, value in candidate.items() if key in PUBLIC_FIELDS}
    if row['subject'] == '英语':
        row['subject'] = '大学英语'
    row['verifiedAt'] = candidate.get('verifiedAt', verified_at)
    row['sha256'] = expected
    row['fileSize'] = source.stat().st_size
    row['documentUrl'] = f'/open-books/{slug}/book.pdf'
    row['licenseTextUrl'] = f'/open-books/{slug}/LICENSE.txt'
    # Full-cover PDFs often contain outlined title text and illustrated formulas.
    # Every book in this batch opens in its original layout; reader choices persist.
    row['preferOriginal'] = bool(candidate.get('preferOriginal', True))
    row['coverUrl'] = None
    cover = None
    policy = candidate.get('coverPolicy', 'subject-default')
    page_attribution = candidate.get('requiredPageAttributionText') or candidate.get('pageAttributionText')
    attribution_url = candidate.get('requiredPageAttributionUrl') or candidate.get('pageAttributionUrl')
    with fitz.open(source) as document:
        require(not document.needs_pass, f'{slug}: encrypted PDF is not supported')
        require(len(document) >= 100 and len(document) == candidate.get('pageCount'), f'{slug}: full-book page count mismatch')
        row['pageCount'] = len(document)
        row['pdfRepaired'] = document.is_repaired
        pages = []
        for page in document:
            text = page.get_text('text', sort=True)
            if page_attribution and page_attribution.rstrip('.') not in text:
                text += '\n' + page_attribution + '\n' + (attribution_url or '') + '\n'
            pages.append(text)
        body = PAGE_BREAK.join(pages)
        require(50000 <= len(body) <= 5000000, f'{slug}: unexpected full-book text length {len(body)}')
        require(body.count('\f') == len(document) - 1, f'{slug}: ambiguous extracted page boundaries')
        if policy == 'pdf-first-page':
            require('openstax' not in row['sourceUrl'].lower(), f'{slug}: OpenStax covers require separate authorization')
            page = document[0]
            pix = page.get_pixmap(matrix=fitz.Matrix(480 / page.rect.width, 480 / page.rect.width), alpha=False)
            picture = Image.frombytes('RGB', (pix.width, pix.height), pix.samples)
            if picture.width != 480:
                picture = picture.resize((480, round(480 * page.rect.height / page.rect.width)), Image.Resampling.LANCZOS)
            buffer = BytesIO()
            picture.save(buffer, 'WEBP', quality=90, method=6)
            cover = buffer.getvalue()
            row['coverUrl'] = f'/open-books/{slug}/cover.webp'
        elif policy not in {'subject-default', 'use-default'}:
            remote_cover = candidate.get('coverUrl')
            if remote_cover:
                require(remote_cover.startswith('https://'), f'{slug}: remote cover must use HTTPS')
                row['coverUrl'] = remote_cover
    body_bytes = body.encode('utf-8')
    require(len(body_bytes) < 16000000, f'{slug}: text exceeds database storage limit')
    row['textLength'] = len(body)
    row['textSha256'] = hashlib.sha256(body_bytes).hexdigest()
    row['textExtractionNote'] = '完整逐页提取，页内 sort=True，以换页符分隔；未截断。原始 PDF 未修改。'
    return {'row': row, 'source': source, 'body': body_bytes, 'cover': cover,
            'license': license_path.read_bytes(), 'attribution': attribution_file(row, license_source)}


def main(inputs, check):
    license_data = json.loads((LICENSES / 'sources.json').read_text(encoding='utf-8'))
    license_index = {row['licenseCode']: row for row in license_data['records']}
    reserved = {row['slug'] for row in json.loads((ROOT / 'db/catalog/github-open-books.json').read_text(encoding='utf-8'))['records']}
    books, seen, dates = [], set(), []
    # Validate every input before creating any public assets.
    for filename in inputs:
        path = Path(filename).resolve(strict=True)
        data = json.loads(path.read_text(encoding='utf-8'))
        require(isinstance(data.get('records'), list) and data['records'], f'No candidate records: {path}')
        verified_at = data.get('verifiedAt', '')
        require(re.fullmatch(r'\d{4}-\d{2}-\d{2}', verified_at), f'Missing verification date: {path}')
        dates.append(verified_at)
        for candidate in data['records']:
            require(candidate.get('slug') not in seen, f"Duplicate input slug: {candidate.get('slug')}")
            seen.add(candidate['slug'])
            books.append(prepare(candidate, path, verified_at, license_index, reserved))
    for book in books:
        row = book['row']
        folder = ASSETS / row['slug']
        pdf = folder / 'book.pdf'
        protect_original(pdf, row['sha256'])
        if check:
            require(pdf.is_file(), f'Missing original PDF: {pdf}')
        elif not pdf.exists():
            folder.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(book['source'], pdf)
        require(digest(pdf) == row['sha256'], f"{row['slug']}: packaged PDF hash mismatch")
        write_file(folder / 'body.txt', book['body'], check)
        write_file(folder / 'LICENSE.txt', book['license'], check)
        write_file(folder / 'ATTRIBUTION.md', book['attribution'], check)
        if book['cover'] is not None:
            write_file(folder / 'cover.webp', book['cover'], check)
    rows = [book['row'] for book in books]
    write_file(MANIFEST, encoded({'schemaVersion': 1, 'verifiedAt': max(dates), 'records': rows}), check)
    write_file(CONFIG, reading_config(rows), check)
    print(json.dumps({'validated' if check else 'packaged': len(rows),
                      'pages': sum(row['pageCount'] for row in rows),
                      'textCharacters': sum(row['textLength'] for row in rows),
                      'pdfBytes': sum(row['fileSize'] for row in rows),
                      'largestPdfBytes': max(row['fileSize'] for row in rows),
                      'covers': sum(book['cover'] is not None for book in books),
                      'books': [{key: row[key] for key in ('slug', 'pageCount', 'textLength', 'fileSize', 'coverUrl', 'preferOriginal')} for row in rows]}, ensure_ascii=True))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifests', nargs='+', help='Reviewed local candidate manifests to combine')
    parser.add_argument('--check', action='store_true', help='Validate outputs without modifying files')
    arguments = parser.parse_args()
    main(arguments.manifests, arguments.check)
