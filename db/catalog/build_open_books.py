#!/usr/bin/env python3
"""Validate bundled, licensed complete books and generate the idempotent V28 seed.

The reviewed manifest and original files are local inputs; this tool never crawls
or executes SQL. Use --check to verify generated SQL without overwriting it.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'frontend/public/open-books'
MANIFEST = ROOT / 'db/catalog/github-open-books.json'
OUTPUT = ROOT / 'backend/src/main/resources/db/migration/V28__seed_complete_open_books.sql'
FOUNDATION_MANIFEST = ROOT / 'db/catalog/github-foundation-books.json'
FOUNDATION_OUTPUT = ROOT / 'backend/src/main/resources/db/migration/V29__seed_foundation_open_books.sql'
LICENSES = {'CC-BY-4.0', 'CC-BY-SA-4.0', 'CC-BY-NC-SA-4.0', 'CC-BY-NC-3.0', 'CC-BY-SA-3.0-US',
            'GFDL-1.2-or-later', 'GFDL-1.3-or-later'}


def sql(value):
    if value is None:
        return 'NULL'
    if isinstance(value, int):
        return str(value)
    # Backslashes must be identical in MySQL's normal mode and H2's MySQL mode.
    marker = '__OPEN_BOOK_BACKSLASH__'
    assert marker not in value
    escaped = value.replace('\\', marker).replace("'", "''")
    literal = "'" + escaped + "'"
    return f"REPLACE({literal}, '{marker}', CHAR(92))" if '\\' in value else literal


def build(manifest=MANIFEST, foundation=False):
    data = json.loads(manifest.read_text(encoding='utf-8'))
    rows = data['records']
    seen = set()
    statements = [
        '-- Generated by db/catalog/build_open_books.py. Do not edit by hand.',
        '-- Original complete PDFs, licences and attribution: frontend/public/open-books/.',
        '-- The PDFs are unchanged. Extracted text is for search and private learning imports.',
        '-- Existing resources, private materials and administrator edits are preserved.',
    ]
    counts = []
    for row in rows:
        slug = row['slug']
        assert re.fullmatch('[a-z0-9-]+', slug) and slug not in seen
        seen.add(slug)
        folder = ASSETS / slug
        document = (folder / 'book.pdf').read_bytes()
        body = (folder / 'body.txt').read_text(encoding='utf-8')
        assert document.startswith(b'%PDF-'), slug
        assert hashlib.sha256(document).hexdigest() == row['sha256'], slug
        maximum = 5000000 if foundation else 1000000
        assert 50000 <= len(body) <= maximum, f'{slug}: unexpected full-book length {len(body)}'
        assert len(body.encode('utf-8')) < 16000000, f'{slug}: body exceeds MEDIUMTEXT capacity'
        assert hashlib.sha256(body.encode('utf-8')).hexdigest() == row['textSha256'], slug
        assert row['pageCount'] >= 100 and row['licenseCode'] in LICENSES, slug
        assert (folder / 'ATTRIBUTION.md').stat().st_size > 200
        cover_url = row.get('coverUrl', f'/open-books/{slug}/cover.webp')
        if cover_url and cover_url.startswith('/open-books/'):
            assert cover_url == f'/open-books/{slug}/cover.webp' and (folder / 'cover.webp').is_file()
        assert row['sourceUrl'].startswith('https://github.com/')
        assert row['licenseUrl'].startswith('https://') and row['downloadUrl'].startswith('https://')
        assert row['author'] and row['publisher'] and row['licenseNote']
        fields = {
            'title': row['title'], 'summary': row['summary'], 'subject': row['subject'],
            'knowledge_points': ','.join(row['knowledgePoints']), 'difficulty_level': 2,
            'estimated_minutes': 0, 'resource_type': 'INTERNAL', 'source_name': row['sourceName'],
            'source_url': row['sourceUrl'], 'author': row['author'], 'license_code': row['licenseCode'],
            'license_url': row['licenseUrl'], 'license_note': row['licenseNote'], 'content_text': body,
            'status': 'PUBLISHED', 'review_note': '完整文件、来源与正文许可已核验；原PDF未修改，保留署名。',
            'resource_kind': 'TEXTBOOK', 'language_code': row['languageCode'], 'coverage_note': row['coverageNote'],
            'download_url': row['downloadUrl'], 'cover_url': cover_url,
            'access_mode': 'OPEN_RESOURCE', 'publisher': row['publisher'], 'education_level': '大学学习',
            'document_url': f'/open-books/{slug}/book.pdf', 'page_count': row['pageCount'],
        }
        statements.append('\n-- ' + row['title'] + f" ({row['pageCount']} pages; {row['licenseCode']})")
        # A GitHub repository may publish several complete volumes. Distinguish
        # them by document path and title while preserving administrator edits.
        identity = ('document_url = ' + sql(fields['document_url']) + ' OR (source_url = '
                    + sql(row['sourceUrl']) + ' AND title = ' + sql(row['title']) + ')') if foundation else ('source_url = ' + sql(row['sourceUrl']))
        statements.append('INSERT INTO study_resource (' + ', '.join(fields) + ')\nSELECT\n  '
                          + ',\n  '.join(sql(value) for value in fields.values())
                          + '\nWHERE NOT EXISTS (SELECT 1 FROM study_resource WHERE '
                          + identity + ');')
        counts.append({'title': row['title'], 'pages': row['pageCount'], 'characters': len(body)})
    return '\n'.join(statements) + '\n', counts


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--foundation', action='store_true', help='Generate the separate V29 foundation-book batch')
    args = parser.parse_args()
    destination = FOUNDATION_OUTPUT if args.foundation else OUTPUT
    output, counts = build(FOUNDATION_MANIFEST if args.foundation else MANIFEST, args.foundation)
    if args.check:
        assert destination.read_text(encoding='utf-8') == output, f'Generated {destination.name} is stale'
    else:
        destination.write_text(output, encoding='utf-8', newline='\n')
    print(json.dumps({'validated': len(counts), 'books': counts}, ensure_ascii=False))
