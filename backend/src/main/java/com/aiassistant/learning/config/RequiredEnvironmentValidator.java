package com.aiassistant.learning.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.Base64;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.context.event.ApplicationEnvironmentPreparedEvent;
import org.springframework.context.ApplicationListener;
import org.springframework.core.env.ConfigurableEnvironment;
import org.springframework.core.env.MapPropertySource;

/**
 * 敏感配置校验与本地开发自适应初始化。
 *
 * <p>设计原则：“本地默认能跑、生产显式严格”。</p>
 * <ul>
 *   <li><b>本地开发模式（默认）</b>：开箱即用。若未配置 JWT 密钥，则在内存中随机生成（重启后旧 Token 失效）；
 *   若未配置加密口令，则自动生成并持久化到 {@code runtime/secret-encryption.key} 中复用，保证落库 API Key 可跨重启解密；
 *   数据库密码默认使用 Docker Compose 默认值 {@code 123456789}。</li>
 *   <li><b>生产环境模式</b>（当 {@code app.security.require-explicit-secrets=true} 或激活 {@code prod}/{@code production} profile）：
 *   三项敏感配置必须显式提供，且满足长度安全要求；任何缺失或保留占位符字面量均会直接中止启动并提示。</li>
 * </ul>
 */
public class RequiredEnvironmentValidator implements ApplicationListener<ApplicationEnvironmentPreparedEvent> {

    private static final Logger log = LoggerFactory.getLogger(RequiredEnvironmentValidator.class);

    /** 开关配置键：是否要求显式配置敏感密钥。 */
    public static final String STRICT_MODE_KEY = "app.security.require-explicit-secrets";

    /** 自定义注入的属性源名称。 */
    public static final String AUTO_GENERATED_PROPERTY_SOURCE_NAME = "autoGeneratedSecuritySecrets";

    /** 默认持久化加密口令文件名。 */
    public static final String DEFAULT_KEY_FILE_NAME = "secret-encryption.key";

    private static final SecureRandom SECURE_RANDOM = new SecureRandom();

    /**
     * 生产模式必填项定义：配置键 -> 对应环境变量名 -> 最小安全长度。
     */
    static final List<RequiredProperty> REQUIRED_PROPERTIES = List.of(
            new RequiredProperty("spring.datasource.password", "SPRING_DATASOURCE_PASSWORD", 1),
            new RequiredProperty("app.jwt.secret", "APP_JWT_SECRET", 32),
            new RequiredProperty("app.secret.encryption-key", "APP_SECRET_ENCRYPTION_KEY", 16)
    );

    @Override
    public void onApplicationEvent(ApplicationEnvironmentPreparedEvent event) {
        validate(event.getEnvironment());
    }

    /**
     * 执行环境校验与开发环境自适应初始化。
     *
     * @param environment Spring 可配置环境
     */
    public static void validate(ConfigurableEnvironment environment) {
        if (isStrictMode(environment)) {
            validateStrict(environment);
        } else {
            ensureDevelopmentSecrets(environment);
        }
    }

    /**
     * 判断当前是否处于严格模式。
     */
    public static boolean isStrictMode(ConfigurableEnvironment environment) {
        if (environment == null) {
            return false;
        }
        Boolean requireExplicit = environment.getProperty(STRICT_MODE_KEY, Boolean.class);
        if (Boolean.TRUE.equals(requireExplicit)) {
            return true;
        }
        for (String profile : environment.getActiveProfiles()) {
            if ("prod".equalsIgnoreCase(profile) || "production".equalsIgnoreCase(profile)) {
                return true;
            }
        }
        return false;
    }

    /**
     * 生产严格校验：逐项检查必须显式提供且达到最小长度。
     */
    static void validateStrict(ConfigurableEnvironment environment) {
        List<String> problems = new ArrayList<>();
        for (RequiredProperty property : REQUIRED_PROPERTIES) {
            String value = resolvePropertyValue(environment, property.key());
            if (value == null || value.isBlank() || value.contains("${")) {
                problems.add("缺少环境变量 " + property.environmentVariable() + "（配置项 " + property.key() + "）");
            } else if (value.trim().length() < property.minLength()) {
                problems.add("环境变量 " + property.environmentVariable() + " 长度至少 " + property.minLength() + " 个字符");
            }
        }
        if (!problems.isEmpty()) {
            throw new IllegalStateException("启动中止，生产模式要求显式配置以下项：" + String.join("；", problems)
                    + "。请参考项目根目录 .env.example 补齐后重试。");
        }
    }

    /**
     * 本地非严格模式：检查敏感项，未配置时自动补齐默认或随机生成。
     */
    static void ensureDevelopmentSecrets(ConfigurableEnvironment environment) {
        if (environment == null) {
            return;
        }
        Map<String, Object> autoProperties = new LinkedHashMap<>();

        // 1. JWT 密钥：缺失或过短时在内存中随机生成
        String jwtSecret = resolvePropertyValue(environment, "app.jwt.secret");
        if (!isValidSecret(jwtSecret, 32)) {
            String generatedJwt = generateRandomSecret(48); // 64 URL-safe chars
            autoProperties.put("app.jwt.secret", generatedJwt);
            autoProperties.put("APP_JWT_SECRET", generatedJwt);
            log.warn("未显式配置 APP_JWT_SECRET，已在内存中随机生成临时 JWT 密钥（应用重启后旧 Token 将失效）。生产环境请通过环境变量显式配置。");
        }

        // 2. 落库加密口令：缺失或过短时持久化到 runtime/ 目录或复用已存文件
        String encryptionKey = resolvePropertyValue(environment, "app.secret.encryption-key");
        if (!isValidSecret(encryptionKey, 16)) {
            Path keyPath = resolveEncryptionKeyPath(environment);
            String persistedKey = getOrGeneratePersistedKey(keyPath);
            autoProperties.put("app.secret.encryption-key", persistedKey);
            autoProperties.put("APP_SECRET_ENCRYPTION_KEY", persistedKey);
        }

        if (!autoProperties.isEmpty()) {
            environment.getPropertySources().addFirst(
                    new MapPropertySource(AUTO_GENERATED_PROPERTY_SOURCE_NAME, autoProperties));
        }
    }

    static boolean isValidSecret(String value, int minLength) {
        if (value == null || value.isBlank() || value.contains("${")) {
            return false;
        }
        return value.trim().length() >= minLength;
    }

    static String resolvePropertyValue(ConfigurableEnvironment environment, String key) {
        try {
            return environment.getProperty(key);
        } catch (IllegalArgumentException unresolvedPlaceholder) {
            return null;
        }
    }

    static Path resolveEncryptionKeyPath(ConfigurableEnvironment environment) {
        String configuredPath = environment != null ? environment.getProperty("app.secret.key-file") : null;
        if (configuredPath != null && !configuredPath.isBlank() && !configuredPath.contains("${")) {
            return Paths.get(configuredPath.trim()).toAbsolutePath().normalize();
        }
        return resolveDefaultRuntimeKeyPath();
    }

    static Path resolveDefaultRuntimeKeyPath() {
        Path direct = Paths.get("runtime", DEFAULT_KEY_FILE_NAME);
        Path parent = Paths.get("..", "runtime", DEFAULT_KEY_FILE_NAME);
        if (!Files.exists(direct) && Files.exists(parent.getParent())) {
            return parent.toAbsolutePath().normalize();
        }
        return direct.toAbsolutePath().normalize();
    }

    static String getOrGeneratePersistedKey(Path keyPath) {
        if (Files.isRegularFile(keyPath)) {
            try {
                String existing = Files.readString(keyPath, StandardCharsets.UTF_8).trim();
                if (isValidSecret(existing, 16)) {
                    log.info("从本地文件复用落库加密口令: {}", keyPath);
                    return existing;
                }
                log.warn("本地口令文件 {} 中的内容无效或不足 16 位，将重新生成", keyPath);
            } catch (IOException e) {
                log.warn("读取本地口令文件 {} 失败: {}，将重新生成", keyPath, e.getMessage());
            }
        }

        String newKey = generateRandomSecret(32); // 43 URL-safe chars
        try {
            if (keyPath.getParent() != null) {
                Files.createDirectories(keyPath.getParent());
            }
            Files.writeString(keyPath, newKey, StandardCharsets.UTF_8);
            log.info("未显式配置 APP_SECRET_ENCRYPTION_KEY，已自动生成口令并持久化至: {}（本地开发重启将自动复用，生产环境请通过环境变量显式配置）", keyPath);
        } catch (IOException e) {
            log.warn("无法将自动生成的口令写入文件 {}: {}，本次运行将使用临时内存口令", keyPath, e.getMessage());
        }
        return newKey;
    }

    static String generateRandomSecret(int byteLength) {
        byte[] bytes = new byte[byteLength];
        SECURE_RANDOM.nextBytes(bytes);
        return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
    }

    /**
     * 必填配置描述。
     */
    record RequiredProperty(String key, String environmentVariable, int minLength) {
    }
}
